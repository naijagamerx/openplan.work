PriorityStyle priorityStyle(String priority) {
  switch (priority.toLowerCase()) {
    case 'urgent':
      return const PriorityStyle(Color(0xFFDC2626), Colors.white);
    case 'high':
      return const PriorityStyle(Color(0xFFEA580C), Colors.white);
    case 'low':
      return const PriorityStyle(Color(0xFF16A34A), Colors.white);
    case 'medium':
    default:
      return const PriorityStyle(Color(0xFFEAB308), Colors.black);
  }
}

